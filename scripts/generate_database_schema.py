#!/usr/bin/env python3
"""Embed the canonical SQL schema for native builds without a runtime file lookup."""
import json
from pathlib import Path
import sys
root = Path(__file__).resolve().parent.parent
source = root / 'scripts/database_schema.sql'
target = root / 'src/database_schema.inc'
content = '/* Generated by scripts/generate_database_schema.py; edit database_schema.sql. */\n' + '\n'.join(json.dumps(line + '\n') for line in source.read_text().splitlines()) + '\n'
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != content:
        raise SystemExit('database_schema.inc is out of date')
else:
    target.write_text(content)
