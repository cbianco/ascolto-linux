#!/usr/bin/env python3
"""Embed the audited, pinned local model manifest in the native manager."""
import argparse
import json
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
source = json.loads((ROOT / 'resources/local-stt-manifest.json').read_text())
if source.get('version') != 1 or len(source.get('models', [])) != 3:
    raise SystemExit('Unsupported local STT manifest')
if [model['id'] for model in source['models']] != ['whisper-turbo-q5', 'parakeet-v3-q8', 'qwen3-asr-1.7b']:
    raise SystemExit('Local STT manifest model order does not match the native ABI')
for model in source['models']:
    for file in model['files']:
        if (Path(file['filename']).name != file['filename'] or
                not re.fullmatch(r'[0-9a-f]{64}', file['sha256']) or
                not re.match(r'https://huggingface\.co/[^/]+/[^/]+/resolve/[0-9a-f]{40}/', file['source_url']) or
                not isinstance(file['bytes'], int) or file['bytes'] <= 0):
            raise SystemExit('Invalid or unpinned local STT artifact')
lines = ['/* Generated by scripts/generate_local_stt_manifest.py. */']
for index, model in enumerate(source['models'], 1):
    lines.append(f'static const artifact_t artifacts_{index}[] = {{')
    for file in model['files']:
        fields = [json.dumps(file['filename']), json.dumps(file['source_url']), json.dumps(file['sha256']), str(file['bytes']) + 'ULL']
        lines.append('    {' + ', '.join(fields) + '},')
    lines.append('};')
lines.append('static const package_t packages[] = { {NULL, 0},')
for index in range(1, 4):
    lines.append(f'    {{artifacts_{index}, sizeof(artifacts_{index}) / sizeof(artifacts_{index}[0])}},')
lines.append('};')
text = '\n'.join(lines) + '\n'
path = ROOT / 'src/local_stt_manifest.inc'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    if not path.exists() or path.read_text() != text:
        raise SystemExit('Native local STT manifest is stale')
else:
    path.write_text(text)
