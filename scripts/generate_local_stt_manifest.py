#!/usr/bin/env python3
"""Embed the audited, pinned local model manifest in the native manager."""
import argparse
import hashlib
import json
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
source = json.loads((ROOT / 'resources/local-stt-manifest.json').read_text())
if source.get('version') != 1 or len(source.get('models', [])) != 5:
    raise SystemExit('Unsupported local STT manifest')
if [model['id'] for model in source['models']] != ['whisper-turbo-q5', 'parakeet-v3-q8', 'qwen3-asr-1.7b', 'nemotron-3.5-q8', 'nemotron-3.5-bf16-ssd']:
    raise SystemExit('Local STT manifest model order does not match the native ABI')
for model in source['models']:
    preparation = model.get('preparation_bytes', 0)
    if not isinstance(preparation, int) or preparation < 0 or preparation > 2**50:
        raise SystemExit('Invalid native preparation workspace size')
    for file in model['files'] + model.get('installed_files', []):
        if (not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9._-]*', file['filename']) or
                not re.fullmatch(r'[0-9a-f]{64}', file['sha256']) or
                ('source_url' in file and not re.match(r'https://huggingface\.co/[^/]+/[^/]+/resolve/[0-9a-f]{40}/', file['source_url'])) or
                not isinstance(file['bytes'], int) or not 0 < file['bytes'] <= 2**50):
            raise SystemExit('Invalid or unpinned local STT artifact')
    if any('source_url' not in file for file in model['files']):
        raise SystemExit('Download artifacts require a pinned URL')
    if bool(preparation) != bool(model.get('installed_files')):
        raise SystemExit('Native preparation requires an installed artifact manifest')
    if sum(file['bytes'] for file in model['files']) + preparation > 2**51:
        raise SystemExit('Native package storage size overflows its supported range')
    if preparation:
        directory = ROOT / 'resources/nemotron-bf16-preparation'
        serialized = (directory / 'recipe.json').read_bytes()
        if hashlib.sha256(serialized).hexdigest() != model.get('preparation_recipe_sha256'):
            raise SystemExit('Native BF16 recipe checksum mismatch')
        recipe = json.loads(serialized)
        original = model['files'][0]
        if original['filename'] != 'model.safetensors' or original['sha256'] != recipe['source_sha256'] or original['bytes'] != recipe['source_bytes']:
            raise SystemExit('Native BF16 recipe input differs from the download manifest')
        for output in recipe['outputs']:
            installed = next((f for f in model['installed_files'] if f['filename'] == output['name']), None)
            if not installed or installed['sha256'] != output['sha256'] or installed['bytes'] != output['bytes']:
                raise SystemExit('Native BF16 recipe output differs from the installed manifest')
            header = directory / output['name'].replace('.gguf', '.header')
            if hashlib.sha256(header.read_bytes()).hexdigest() != output['header_sha256']:
                raise SystemExit('Native BF16 header checksum mismatch')
        if hashlib.sha256((directory / 'constants.bin').read_bytes()).hexdigest() != recipe['constants_sha256']:
            raise SystemExit('Native BF16 constants checksum mismatch')
lines = ['/* Generated by scripts/generate_local_stt_manifest.py. */']
for index, model in enumerate(source['models'], 1):
    lines.append(f'static const artifact_t artifacts_{index}[] = {{')
    for file in model['files']:
        fields = [json.dumps(file['filename']), json.dumps(file['source_url']), json.dumps(file['sha256']), str(file['bytes']) + 'ULL']
        lines.append('    {' + ', '.join(fields) + '},')
    lines.append('};')
    if model.get('installed_files'):
        lines.append(f'static const artifact_t installed_{index}[] = {{')
        for file in model['installed_files']:
            fields = [json.dumps(file['filename']), 'NULL', json.dumps(file['sha256']), str(file['bytes']) + 'ULL']
            lines.append('    {' + ', '.join(fields) + '},')
        lines.append('};')
lines.append('static const package_t packages[] = { {NULL, 0, NULL, 0, 0},')
for index, model in enumerate(source['models'], 1):
    installed = f'installed_{index}, sizeof(installed_{index}) / sizeof(installed_{index}[0])' if model.get('installed_files') else 'NULL, 0'
    lines.append(f'    {{artifacts_{index}, sizeof(artifacts_{index}) / sizeof(artifacts_{index}[0]), {installed}, {model.get("preparation_bytes", 0)}ULL}},')
lines.append('};')
text = '\n'.join(lines) + '\n'
path = ROOT / 'src/local_stt_manifest.inc'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    if not path.exists() or path.read_text() != text:
        raise SystemExit('Native local STT manifest is stale')
else:
    path.write_text(text)
